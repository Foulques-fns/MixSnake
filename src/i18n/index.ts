const DICTS: Record<LangId, Dict> = { en, fr, es, de, pt, it, ja };

export function detectLang(): LangId {
  if (typeof navigator === "undefined") return "en";
  const langs = navigator.languages ?? [navigator.language];
  for (const l of langs) {
    const code = l.slice(0, 2).toLowerCase() as LangId;
    if (DICTS[code]) return code;
  }
  return "en";
}

export function resolveLang(setting: string): LangId {
  if (setting === "auto") return detectLang();
  return (DICTS[setting as LangId] ? setting : "en") as LangId;
}

export type TFunc = (key: keyof Dict, vars?: Record<string, string | number>) => string;

export function makeT(lang: LangId): TFunc {
  const dict = DICTS[lang] ?? en;
  return (key, vars) => {
    let s: string = dict[key] ?? en[key] ?? String(key);
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    }
    return s;
  };
}
